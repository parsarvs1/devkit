// Get example for a specific type
export function getGitignoreExample(type: string): string {
  return gitignoreTemplates[type] || gitignoreTemplates["default"];
}

// Generate gitignore based on selected types
export function generateGitignore(types: string[]): string {
  const filteredTypes = types.filter(
    (t) => gitignoreTemplates[t as keyof typeof gitignoreTemplates]
  );

  if (filteredTypes.length === 0) {
    return gitignoreTemplates["default"];
  }

  return filteredTypes
    .map((type) => `# ${type.charAt(0).toUpperCase() + type.slice(1)}\n${gitignoreTemplates[type as keyof typeof gitignoreTemplates]}`)
    .join("\n---\n");
}

// Check if a template exists
export function hasTemplate(type: string): boolean {
  return type in gitignoreTemplates;
}
